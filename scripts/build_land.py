"""Build india-atlas/js/land.js (a coastline for the custom 'Antique' basemap) from Natural Earth 50m land.

Usage: python -I scripts/build_land.py <ne_50m_land.geojson> <out_js>
Natural Earth data is public domain (naturalearthdata.com). Output: window.ATLAS_LAND = [ polygon, ... ],
each polygon = [outerRing, ...holes], rings as [lat, lon], clipped to the working box and simplified.
"""
import json
import os
import sys

SRC, OUT = sys.argv[1], sys.argv[2]
BOX = (38.0, 135.0, -16.0, 56.0)  # lon0, lon1, lat0, lat1
TOL = 0.018                        # Douglas-Peucker tolerance in degrees (~2 km)


def clip(ring):
    """Sutherland-Hodgman clip of a [lon, lat] ring against BOX."""
    lon0, lon1, lat0, lat1 = BOX
    pts = ring[:-1] if ring[0] == ring[-1] else ring[:]
    edges = [
        (lambda p: p[0] >= lon0, lambda a, b: [lon0, a[1] + (lon0 - a[0]) / (b[0] - a[0]) * (b[1] - a[1])]),
        (lambda p: p[0] <= lon1, lambda a, b: [lon1, a[1] + (lon1 - a[0]) / (b[0] - a[0]) * (b[1] - a[1])]),
        (lambda p: p[1] >= lat0, lambda a, b: [a[0] + (lat0 - a[1]) / (b[1] - a[1]) * (b[0] - a[0]), lat0]),
        (lambda p: p[1] <= lat1, lambda a, b: [a[0] + (lat1 - a[1]) / (b[1] - a[1]) * (b[0] - a[0]), lat1]),
    ]
    for inside, inter in edges:
        out = []
        for i in range(len(pts)):
            cur, prev = pts[i], pts[i - 1]
            ci, pi = inside(cur), inside(prev)
            if ci != pi:
                out.append(inter(prev, cur))
            if ci:
                out.append(cur)
        pts = out
        if len(pts) < 3:
            return []
    pts.append(pts[0])
    return pts


def dp(points, tol):
    if len(points) < 4:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]
        bx, by = points[b]
        dx, dy = bx - ax, by - ay
        den = dx * dx + dy * dy
        best, idx = -1.0, -1
        for i in range(a + 1, b):
            px, py = points[i]
            if den == 0:
                d = ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
            else:
                t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / den))
                d = ((px - (ax + t * dx)) ** 2 + (py - (ay + t * dy)) ** 2) ** 0.5
            if d > best:
                best, idx = d, i
        if best > tol:
            keep[idx] = True
            stack.append((a, idx))
            stack.append((idx, b))
    return [p for p, k in zip(points, keep) if k]


def area(ring):
    s = 0.0
    for i in range(len(ring) - 1):
        s += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1]
    return abs(s) / 2


gj = json.load(open(SRC, encoding='utf-8'))
polys = []
for f in gj['features']:
    g = f['geometry']
    parts = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    for rings in parts:
        outer = clip(rings[0])
        if not outer or area(outer) < 0.004:
            continue
        out = [[[round(y, 3), round(x, 3)] for x, y in dp(outer, TOL)]]
        for h in rings[1:]:
            hc = clip(h)
            if hc and area(hc) > 0.01:
                out.append([[round(y, 3), round(x, 3)] for x, y in dp(hc, TOL)])
        if len(out[0]) >= 4:
            polys.append(out)

with open(OUT, 'w', encoding='utf-8') as fh:
    fh.write('/* Generated by scripts/build_land.py from Natural Earth 50m land (public domain). Rings are [lat, lon]. */\n')
    fh.write('window.ATLAS_LAND = ')
    json.dump(polys, fh, separators=(',', ':'))
    fh.write(';\n')
print('polygons:', len(polys), 'vertices:', sum(len(r) for p in polys for r in p), 'bytes:', os.path.getsize(OUT))
