// Writes india-atlas/data/atlas.json (eras, routes, people, rivers, works) for non-JS tools such as the Python CLI.
// Usage: node scripts/export_data.js
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { load } = require('./atlas_data');

const { ERAS, ROUTES, PEOPLE, RIVERS } = load();
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'india-atlas', 'js', 'works.js'), 'utf8'), sandbox);

const dir = path.join(__dirname, '..', 'india-atlas', 'data');
fs.mkdirSync(dir, { recursive: true });
const data = {
  note: 'Generated by scripts/export_data.js. Boundaries live in ../geojson/. Coordinates are [lat, lon].',
  eras: ERAS.map((e, i) => Object.assign({ index: i }, e)),
  routes: ROUTES,
  people: PEOPLE,
  rivers: RIVERS,
  works: sandbox.window.ATLAS_WORKS
};
fs.writeFileSync(path.join(dir, 'atlas.json'), JSON.stringify(data));
console.log('wrote', path.join(dir, 'atlas.json'), fs.statSync(path.join(dir, 'atlas.json')).size, 'bytes');
