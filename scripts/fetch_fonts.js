#!/usr/bin/env node
/*
 * Self-hosts the site's fonts so visitors' browsers never contact Google (their IP address would otherwise go to Google on
 * every page load, which is a privacy problem under EU rules). All seven families are SIL Open Font License 1.1, which allows
 * bundling and redistribution provided the licence text travels with them (saved in india-atlas/fonts/licenses/).
 *
 * Downloads the woff2 files for the Latin, Latin-extended (IAST diacritics such as ā ṇ ś) and Devanagari subsets that the
 * site uses, writes india-atlas/css/fonts.css and india-atlas/fonts/. Run once; the output is committed.
 *   node scripts/fetch_fonts.js
 */
'use strict';
const fs = require('fs'), path = require('path');
const OUT = path.join(__dirname, '..', 'india-atlas'), FONTS = path.join(OUT, 'fonts'), LIC = path.join(FONTS, 'licenses');
const SUBSETS = new Set(['latin', 'latin-ext', 'devanagari']);
const FAMILIES = 'family=Cormorant+Garamond:ital,wght@0,500;0,600;0,700;1,500;1,600&family=Cinzel:wght@500;600;700&family=Noto+Serif:wght@400;600;700&family=Noto+Serif+Devanagari:wght@400;600;700&family=Noto+Sans:wght@400;500;600&family=Noto+Sans+Devanagari:wght@400;500;600&family=Amita:wght@400;700&display=swap';
const LICENCE_DIRS = { 'Cormorant Garamond': 'cormorantgaramond', Cinzel: 'cinzel', 'Noto Serif': 'notoserif', 'Noto Serif Devanagari': 'notoserifdevanagari', 'Noto Sans': 'notosans', 'Noto Sans Devanagari': 'notosansdevanagari', Amita: 'amita' };
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';   // a browser UA makes Google return woff2

const get = async (url, bin) => { const r = await fetch(url, { headers: { 'User-Agent': UA } }); if (!r.ok) throw new Error(r.status + ' ' + url); return bin ? Buffer.from(await r.arrayBuffer()) : r.text(); };
const slug = (s) => s.toLowerCase().replace(/\s+/g, '-');

(async () => {
  fs.mkdirSync(LIC, { recursive: true });
  const css = await get('https://fonts.googleapis.com/css2?' + FAMILIES);
  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
  const prop = (b, k) => { const m = new RegExp(k + '\\s*:\\s*([^;]+);').exec(b); return m ? m[1].trim() : ''; };
  const seen = new Map(), faces = []; let bytes = 0;
  for (const [, subset, body] of blocks) {
    if (!SUBSETS.has(subset)) continue;
    const family = prop(body, 'font-family').replace(/['"]/g, ''), style = prop(body, 'font-style'), weight = prop(body, 'font-weight'), range = prop(body, 'unicode-range');
    const url = /url\(([^)]+)\)/.exec(prop(body, 'src'))[1];
    let file = seen.get(url);
    if (!file) {
      file = slug(family) + '-' + subset + '-' + weight.replace(/\s+/g, '-') + (style === 'italic' ? '-italic' : '') + '.woff2';
      const buf = await get(url, true); fs.writeFileSync(path.join(FONTS, file), buf); bytes += buf.length; seen.set(url, file);
    }
    faces.push('@font-face{font-family:\'' + family + '\';font-style:' + style + ';font-weight:' + weight + ';font-display:swap;src:url(../fonts/' + file + ') format(\'woff2\');unicode-range:' + range + '}');
  }
  fs.writeFileSync(path.join(OUT, 'css', 'fonts.css'), '/* Self-hosted copies of the fonts the site uses (SIL Open Font License 1.1; texts in ../fonts/licenses/). Generated by scripts/fetch_fonts.js. */\n' + faces.join('\n') + '\n');
  for (const [name, dir] of Object.entries(LICENCE_DIRS)) fs.writeFileSync(path.join(LIC, slug(name) + '-OFL.txt'), await get('https://raw.githubusercontent.com/google/fonts/main/ofl/' + dir + '/OFL.txt'));
  console.log(faces.length + ' @font-face rules, ' + seen.size + ' files, ' + Math.round(bytes / 1024) + ' KB, ' + Object.keys(LICENCE_DIRS).length + ' licence texts');
})().catch((e) => { console.error(e); process.exit(1); });
